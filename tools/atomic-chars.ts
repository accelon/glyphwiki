/**
 * atomic-chars.ts — **獨體字表**（永不拆分）。
 *
 * **判準（師父第 108 輪的裁定）**：
 *   > 「105 列，**只要墨是一團，都可以按獨體字處理**。」
 *
 * 也就是：**畫法看起來是一團墨 → 獨體** ✓（即使《說文》說「从某」也一樣 ✓，例
 * `丈`＝从又持十 ✓、`不`＝从一 ✓、`丘`＝从北 ✓、`二`＝从耦一 ✓——這些都**留在表內** ✓）。
 * 理由：今天的字形是**隸變之後的宋體／明朝體** ✓，許慎沒見過 ✗；說文說的拆分用宋體的字形邏輯
 * 解不了 ✗（§6.19）——所以**視覺優先** ✓、說文只當參考 ✓。
 *
 * 下面的 `EXCLUDE` 不是依說文移出的 ✗，而是依**硬證據：畫法有 >= 2 個引用**（＝真的兩塊墨 ✓）：
 *   `乩`＝占＋乚（2 引用 ✓）、`亨`＝亠＋口＋了（3 引用 ✓）、`谷`（2 引用 ✓）。
 * 這三個在宋體下**本來就不是一團墨** ✓，所以不適用上面那條裁定 ✓。
 *
 * 先以**康熙 214 部首**為基礎（部首絕大多數在宋體下都是一團墨 ✓），標記為**草稿待審**：
 * 漏收的請補、誤收的（例 `見`、`高`、`黃`）請刪。
 */

/** 康熙 214 部首（其中多數為獨體；逐字待審） */
const KANGXI_214 =
  "一丨丶丿乙亅二亠人儿入八冂冖冫几凵刀力勹匕匚匸十卜卩厂厶又口囗土士夂夊夕大女子宀寸小尢尸屮山巛工己巾干幺广廴廾弋弓彐彡彳心戈戶手支攴文斗斤方无日曰月木欠止歹殳毋比毛氏气水火爪父爻爿片牙牛犬玄玉瓜瓦甘生用田疋疒癶白皮皿目矛矢石示禸禾穴立竹米糸缶网羊羽老而耒耳聿肉臣自至臼舌舛舟艮色艸虍虫血行衣襾見角言谷豆豕豸貝赤走足身車辛辰辵邑酉釆里金長門阜隶隹雨靑非面革韋韭音頁風飛食首香馬骨高髟鬥鬲鬼魚鳥鹵鹿麥麻黃黍黑黹黽鼎鼓鼠鼻齊齒龍龜龠";

/** 常見的獨體字（非部首，但文字學上不拆）——草稿待審 */
const EXTRA = "丈与丏不丐丘丙丞乩乎乒乓亞亟亡亦亥亨京亭亮亳亟事于云互五井亞亢交亦亨亳";

/** 第 97 輪（師父指示）：**只需分辨「獨體」還是「組合」，不必分象形六書** ✓
 *  （那是連文字學家都沒有共識的事 ✗）。判準是**實用**的：
 *    * 畫法裡有 **>= 2 塊墨**（引用 >= 2，或引用 ＋ 手畫分群 >= 2）→ **組合** ✓
 *    * 只有一團墨 → **獨體** ✓（例 `巛` 無拆分 ✓、`廾` 是會意字但可直接用獨體處理 ✓）
 *    * `丈`＝又＋十 是**理據拆分** ✓，但「我們很難用又十組出來」→ **按獨體處理** ✓（師父的判準 ✓）
 *
 *  這裡放的是**師父已裁定要移出獨體表**的字（原為草稿誤收 ✓）：
 *    `乩`（占＋乚 ✓，畫法有 2 個引用 ✓）、`亨`（亠＋口＋了 ✓，3 個引用 ✓）、
 *    `谷`（畫法 2 個引用 ✓）——三者都是**組合** ✓。 */
/* 第 109 輪：師父裁定「清。」＋選 A，並同意 **A′**（見 §6.21）——
   把「手畫、但明顯是合體」的 8 個移出獨體表 ✓：
     `麥`＝來＋夂、`食`＝人＋良、`頁`＝丆＋貝、`音`＝立＋日、`面`＝丆＋囬、
     `首`＝䒑＋自、`角`＝⺈＋用、`長`＝厂＋二
   代價：`䴺來` 不再走「換部件」✗，改走「**部件檢字**」✓（打 `䴺麥去` 照樣組得出來 ✓
   ——`麥`／`咅` 才是畫法真的引用的 ✓）；`來` 變成「在結構階層裡、但沒有墨可換」✓
   （誠實：看不到的墨不能假裝能換 ✓）。真正兩全的辦法是把 `麥` 重畫成引用 `來`＋`夂` ✓（改畫法 ✗）。 */
const EXCLUDE = new Set<number>(Array.from("乩亨谷亟网至邑金骨髟鬼麻黑黽鼓鼻龍龠角長面音頁食首麥").map((ch) => ch.codePointAt(0)!));

const ATOMIC = new Set<number>(
  Array.from(KANGXI_214 + EXTRA)
    .map((ch) => ch.codePointAt(0)!)
    .filter((cp) => !EXCLUDE.has(cp)),
);

/** 這個碼位是不是獨體字（＝永不拆分） */
export function isAtomic(cp: number): boolean {
  return ATOMIC.has(cp);
}

/** 表的大小（供報告） */
export function atomicCount(): number {
  return ATOMIC.size;
}
